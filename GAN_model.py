def build_scn(cre_info, waypoints, del_acid, filename):
    acid  = cre_info['acid']
    first = waypoints[0]
    lines = [
        f'#{filename}\n',
        '00:00:00.00>TRAIL ON\n',
        '00:00:00.00>PLUGIN TRACKLOG\n',
        '\n',
        f"00:00:00.00>  CRE  {acid}     {cre_info['actype']}     "
        f"{first['lat']:.4f}   {first['lon']:.4f} "
        f"{cre_info['hdg']:.1f}       "
        f"{first['alt']:.1f} \t{first['spd']:.1f}\n",
    ]
    for i, wpt in enumerate(waypoints):
        t   = _s2t(i + 1)
        tag = f"{acid}{wpt['wpt_idx']:03d}"
        lines += [
            f"{t}> ADDWPT {acid}   {wpt['lat']:.4f}   \t{wpt['lon']:.4f}\n",
            f"{t}> {acid}  AT {tag} DO ALT {acid}  \t{wpt['alt']:.1f}\n",
            f"{t}> {acid}  AT {tag} DO SPD {acid}  \t{wpt['spd']:.1f}\n",
        ]
    if del_acid:
        t_del = _s2t(len(waypoints) + 1)
        tag   = f"{acid}{len(waypoints):03d}"
        lines.append(f"{t_del}> {acid}  AT {tag} DO DEL    \t{del_acid} \n")
    return lines

