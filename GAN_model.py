# ── Time utilities ────────────────────────────────────────────────────────────

def _t2s(t: str) -> float:
    """HH:MM:SS.ss -> float seconds."""
    h, m, s = t.split(':')
    return int(h) * 3600 + int(m) * 60 + float(s)

def _s2t(t) -> str:
    """float seconds -> HH:MM:SS.ss"""
    if t is None:
        return '00:00:00.00'
    t = float(t)
    h = int(t // 3600);  t -= h * 3600
    m = int(t // 60);    s  = t - m * 60
    return f'{h:02d}:{m:02d}:{s:05.2f}'


# ── Geospatial utilities ──────────────────────────────────────────────────────

_R_NM = 3440.065

def haversine_nm(lat1, lon1, lat2, lon2) -> float:
    lat1, lon1, lat2, lon2 = map(math.radians, [lat1, lon1, lat2, lon2])
    dlat = lat2 - lat1;  dlon = lon2 - lon1
    a = math.sin(dlat/2)**2 + math.cos(lat1)*math.cos(lat2)*math.sin(dlon/2)**2
    return 2 * _R_NM * math.asin(math.sqrt(a))

def find_closest_approach(wpts1: list, wpts2: list):
    best_d, best_i, best_j = float('inf'), 0, 0
    step = max(1, len(wpts1) // 100)
    for i in range(0, len(wpts1), step):
        for j in range(0, len(wpts2), step):
            d = haversine_nm(wpts1[i]['lat'], wpts1[i]['lon'],
                             wpts2[j]['lat'], wpts2[j]['lon'])
            if d < best_d:
                best_d, best_i, best_j = d, i, j
    r = min(step * 2, 40)
    for i in range(max(0, best_i - r), min(len(wpts1), best_i + r)):
        for j in range(max(0, best_j - r), min(len(wpts2), best_j + r)):
            d = haversine_nm(wpts1[i]['lat'], wpts1[i]['lon'],
                             wpts2[j]['lat'], wpts2[j]['lon'])
            if d < best_d:
                best_d, best_i, best_j = d, i, j
    return best_i, best_j, best_d


