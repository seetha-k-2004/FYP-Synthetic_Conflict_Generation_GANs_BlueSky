def find_scn_for_acid(scn_folder: str, acid: str) -> str:
    pattern = os.path.join(scn_folder, f'*{acid}*.scn')
    matches = glob.glob(pattern)
    if not matches:
        raise FileNotFoundError(
            f"No SCN file found for acid='{acid}' in '{scn_folder}'\n"
            f"  (searched: {pattern})")
    return matches[0]

def find_preconflict_csv(preconflict_folder: str, acid1: str, acid2: str) -> str:
    for csv_path in glob.glob(os.path.join(preconflict_folder, '*.csv')):
        name = os.path.basename(csv_path)
        if acid1 in name and acid2 in name:
            return csv_path
    # Fallback: check acid values inside each CSV
    for csv_path in glob.glob(os.path.join(preconflict_folder, '*.csv')):
        try:
            df = pd.read_csv(csv_path, nrows=200)
            if 'acid' in df.columns:
                acids_in_file = set(df['acid'].unique())
                if acid1 in acids_in_file and acid2 in acids_in_file:
                    return csv_path
        except Exception:
            continue
    raise FileNotFoundError(
        f"No preconflict CSV found for acids '{acid1}' and '{acid2}' "
        f"in '{preconflict_folder}'")


