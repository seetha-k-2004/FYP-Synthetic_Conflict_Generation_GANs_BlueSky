_FEATURES = ['lat', 'lon', 'heading', 'alt', 'ground_speed']
_N_STEPS  = 480
_N_FEAT   = len(_FEATURES)
TRAJ_DIM  = _N_STEPS * _N_FEAT

def extract_features(df: pd.DataFrame, acid: str):
    sub = (df[df['acid'] == acid]
           .sort_values('sim_time')
           .reset_index(drop=True))
    if sub.empty:
        raise ValueError(f"No rows found for aircraft '{acid}' in CSV.")
    data = sub[_FEATURES].values.astype(np.float32)
    if len(data) > _N_STEPS:
        data = data[:_N_STEPS]
    elif len(data) < _N_STEPS:
        pad  = np.tile(data[-1], (_N_STEPS - len(data), 1))
        data = np.vstack([data, pad])
    stats = {'min': data.min(axis=0), 'max': data.max(axis=0)}
    norm  = (data - stats['min']) / (stats['max'] - stats['min'] + 1e-8) * 2 - 1
    return norm.astype(np.float32), stats, data

def denorm(arr: np.ndarray, stats: dict) -> np.ndarray:
    return (arr + 1) / 2 * (stats['max'] - stats['min'] + 1e-8) + stats['min']


# ── GAN ───────────────────────────────────────────────────────────────────────

LATENT_DIM = 64

def build_generator(latent_dim=LATENT_DIM, output_dim=TRAJ_DIM):
    z = keras.Input(shape=(latent_dim,), name='noise')
    x = layers.Dense(256, use_bias=False)(z)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Dense(512, use_bias=False)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Dense(256, use_bias=False)(x)
    x = layers.BatchNormalization(momentum=0.9)(x)
    x = layers.LeakyReLU(0.2)(x)
    out = layers.Dense(output_dim, activation='tanh', name='trajectory')(x)
    return Model(inputs=z, outputs=out, name='Generator')

def build_discriminator(input_dim=TRAJ_DIM):
    traj = keras.Input(shape=(input_dim,), name='trajectory')
    x = layers.Dense(256)(traj)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(128)(x)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(64)(x)
    x = layers.LeakyReLU(0.2)(x)
    out = layers.Dense(1, activation='sigmoid', name='real_prob')(x)
    return Model(inputs=traj, outputs=out, name='Discriminator')

class TrajectoryGAN:
    def __init__(self, latent_dim=LATENT_DIM, traj_dim=TRAJ_DIM,
                 lr_g=2e-4, lr_d=2e-4, seed=42):
        tf.random.set_seed(seed);  np.random.seed(seed)
        self.latent_dim = latent_dim;  self.traj_dim = traj_dim
        self.G = build_generator(latent_dim, traj_dim)
        self.D = build_discriminator(traj_dim)
        self.opt_g = optimizers.Adam(learning_rate=lr_g, beta_1=0.5)
        self.opt_d = optimizers.Adam(learning_rate=lr_d, beta_1=0.5)
        self.bce   = losses.BinaryCrossentropy()

    def _noise(self, n):
        return tf.random.normal((n, self.latent_dim))

    def _augment(self, real_flat, n=8, sigma=0.02):
        tiled = np.tile(real_flat, (n, 1)).astype(np.float32)
        noisy = tiled + np.random.normal(0, sigma, tiled.shape).astype(np.float32)
        return tf.constant(np.clip(noisy, -1.0, 1.0))

    @tf.function
    def _train_d(self, real_batch, fake_batch):
        ones  = tf.ones ((tf.shape(real_batch)[0], 1))
        zeros = tf.zeros((tf.shape(fake_batch)[0], 1))
        with tf.GradientTape() as tape:
            loss = (self.bce(ones,  self.D(real_batch, training=True)) +
                    self.bce(zeros, self.D(fake_batch, training=True)))
        grads = tape.gradient(loss, self.D.trainable_variables)
        self.opt_d.apply_gradients(zip(grads, self.D.trainable_variables))
        return loss

    @tf.function
    def _train_g(self, batch_size):
        z    = self._noise(batch_size)
        ones = tf.ones((batch_size, 1))
        with tf.GradientTape() as tape:
            fake = self.G(z, training=True)
            loss = self.bce(ones, self.D(fake, training=False))
        grads = tape.gradient(loss, self.G.trainable_variables)
        self.opt_g.apply_gradients(zip(grads, self.G.trainable_variables))
        return loss

    def train(self, traj1_norm, traj2_norm, epochs=500, batch_size=8, verbose=True):
        flat1 = traj1_norm.flatten().reshape(1, -1)
        flat2 = traj2_norm.flatten().reshape(1, -1)
        d_hist, g_hist = [], []
        for epoch in range(1, epochs + 1):
            for flat in (flat1, flat2):
                real_batch = self._augment(flat, n=batch_size)
                fake_batch = self.G(self._noise(batch_size), training=False)
                d_loss = self._train_d(real_batch, fake_batch)
                g_loss = self._train_g(batch_size)
            d_hist.append(float(d_loss));  g_hist.append(float(g_loss))
            if verbose and epoch % 100 == 0:
                print(f"  Epoch {epoch:5d}/{epochs} | "
                      f"D_loss={d_loss:.4f} | G_loss={g_loss:.4f}")
        return d_hist, g_hist

    def save(self, path):
        self.G.save_weights(os.path.join(path, 'generator.weights.h5'))
        self.D.save_weights(os.path.join(path, 'discriminator.weights.h5'))
        print(f"  [GAN] Weights saved -> {path}")

    def load(self, path):
        self.G.load_weights(os.path.join(path, 'generator.weights.h5'))
        self.D.load_weights(os.path.join(path, 'discriminator.weights.h5'))
        print(f"  [GAN] Weights loaded <- {path}")


# ── Waypoint updater ──────────────────────────────────────────────────────────

def update_waypoints(orig_wpts: list,
                     lat_shift: float,
                     lon_shift: float) -> list:
    """
    Apply a constant uniform lat/lon offset to every waypoint (rigid body
    shift).  Alt and spd are carried over unchanged from the original SCN.
    """
    new_wpts = []
    for wpt in orig_wpts:
        w = dict(wpt)
        w['lat'] = wpt['lat'] + lat_shift
        w['lon'] = wpt['lon'] + lon_shift
        new_wpts.append(w)
    return new_wpts


