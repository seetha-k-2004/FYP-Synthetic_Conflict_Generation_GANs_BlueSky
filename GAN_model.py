def parse_scn(scn_path: str) -> dict:
    with open(scn_path, 'r') as fh:
        raw_lines = fh.readlines()

    cre_re    = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s+CRE\s+(\w+)\s+(\w+)\s+'
        r'([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)',
        re.IGNORECASE)
    addwpt_re = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s+ADDWPT\s+\w+\s+([\d.\-]+)\s+([\d.\-]+)',
        re.IGNORECASE)
    alt_re    = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s+\w+\s+AT\s+\w+\s+DO\s+ALT\s+\w+\s+([\d.\-]+)',
        re.IGNORECASE)
    spd_re    = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s+\w+\s+AT\s+\w+\s+DO\s+SPD\s+\w+\s+([\d.\-]+)',
        re.IGNORECASE)
    del_re    = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s+\w+\s+AT\s+\w+\s+DO\s+DEL\s+(\w+)',
        re.IGNORECASE)

    cre_line = None
    wpt_map, alt_map, spd_map = {}, {}, {}
    del_acid = None

    for line in raw_lines:
        line = line.rstrip('\n').strip()
        m = cre_re.match(line)
        if m:
            cre_line = dict(acid=m.group(2), actype=m.group(3),
                            lat=float(m.group(4)), lon=float(m.group(5)),
                            hdg=float(m.group(6)), alt=float(m.group(7)),
                            spd=float(m.group(8)))
            continue
        m = addwpt_re.match(line)
        if m:
            t = _t2s(m.group(1))
            wpt_map[t] = {'lat': float(m.group(2)), 'lon': float(m.group(3)),
                          'time_str': m.group(1)}
            continue
        m = alt_re.match(line)
        if m:
            alt_map[_t2s(m.group(1))] = float(m.group(2))
            continue
        m = spd_re.match(line)
        if m:
            spd_map[_t2s(m.group(1))] = float(m.group(2))
            continue
        m = del_re.match(line)
        if m:
            del_acid = m.group(2).strip()

    prev_alt = cre_line['alt'] if cre_line else 0.0
    prev_spd = cre_line['spd'] if cre_line else 0.0
    waypoints = []
    for idx, t in enumerate(sorted(wpt_map), start=1):
        alt = alt_map.get(t, alt_map.get(t + 1, prev_alt))
        spd = spd_map.get(t, spd_map.get(t + 1, prev_spd))
        waypoints.append(dict(wpt_idx=idx, time_s=t,
                               time_str=wpt_map[t]['time_str'],
                               lat=wpt_map[t]['lat'], lon=wpt_map[t]['lon'],
                               alt=alt, spd=spd))
        prev_alt, prev_spd = alt, spd

    print(f"[SCN] {os.path.basename(scn_path)}: "
          f"{len(waypoints)} waypoints | AC={cre_line['acid'] if cre_line else '?'}")
    return dict(cre=cre_line, waypoints=waypoints, del_acid=del_acid)

def parse_conflict_scn(scn_path: str) -> dict:
    with open(scn_path, 'r') as fh:
        lines = fh.readlines()

    inter_re = re.compile(
        r'#.*Intersection.*lat=([\d.\-]+),\s*lon=([\d.\-]+)', re.IGNORECASE)
    call_re  = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>\s*CALL\s+([\w.\-]+\.scn)', re.IGNORECASE)
    quit_re  = re.compile(
        r'(\d{2}:\d{2}:\d{2}\.\d{2})>QUIT', re.IGNORECASE)

    info = dict(intersection=None,
                ac1_scn=None, ac2_scn=None,
                ac1_call_time=None, ac2_call_time=None,
                quit_time=None)
    call_count = 0

    for line in lines:
        m = inter_re.search(line)
        if m:
            info['intersection'] = (float(m.group(1)), float(m.group(2)))
        m = call_re.search(line)
        if m:
            call_count += 1
            t = _t2s(m.group(1))
            if call_count == 1:
                info['ac1_call_time'] = t
                info['ac1_scn'] = m.group(2)
            else:
                info['ac2_call_time'] = t
                info['ac2_scn'] = m.group(2)
        m = quit_re.search(line)
        if m:
            info['quit_time'] = _t2s(m.group(1))

    print(f"[Conflict SCN] intersection={info['intersection']} | "
          f"AC1 call @ {_s2t(info['ac1_call_time'])} | "
          f"AC2 call @ {_s2t(info['ac2_call_time'])}")
    return info


